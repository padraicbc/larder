package app.larder

import android.Manifest
import android.annotation.SuppressLint
import android.content.Intent
import android.content.pm.ApplicationInfo
import android.content.pm.PackageManager
import android.net.Uri
import android.os.Bundle
import android.provider.MediaStore
import android.view.View
import android.webkit.CookieManager
import android.webkit.PermissionRequest
import android.webkit.ValueCallback
import android.webkit.WebChromeClient
import android.webkit.WebResourceRequest
import android.webkit.WebView
import android.webkit.WebViewClient
import android.widget.FrameLayout
import android.widget.TextView
import android.widget.Toast
import androidx.activity.OnBackPressedCallback
import androidx.activity.result.contract.ActivityResultContracts
import androidx.appcompat.app.AppCompatActivity
import androidx.core.content.ContextCompat
import androidx.core.content.FileProvider
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat
import java.io.File
import java.net.HttpURLConnection
import java.net.URL
import kotlin.concurrent.thread
import larder.Larder // generated by gomobile from backend/mobile

/**
 * Runs the Go server in-process and shows the web app in a full-screen WebView.
 * The only Android-specific features are the photo picker/camera and the back button.
 */
class MainActivity : AppCompatActivity() {

    private lateinit var web: WebView
    private var pendingFiles: ValueCallback<Array<Uri>>? = null
    private var cameraPhoto: Uri? = null

    // Camera permission, asked for the first time the page (barcode scanner) or the
    // photo picker needs it. `afterCameraAnswer` runs once the user has answered.
    private var pendingCameraRequest: PermissionRequest? = null
    private var afterCameraAnswer: (() -> Unit)? = null

    private val requestCamera =
        registerForActivityResult(ActivityResultContracts.RequestPermission()) { granted ->
            val request = pendingCameraRequest
            pendingCameraRequest = null
            if (request != null) {
                if (granted) request.grant(arrayOf(PermissionRequest.RESOURCE_VIDEO_CAPTURE)) else request.deny()
            }
            val next = afterCameraAnswer
            afterCameraAnswer = null
            next?.invoke()
        }

    private fun hasCamera() =
        ContextCompat.checkSelfPermission(this, Manifest.permission.CAMERA) == PackageManager.PERMISSION_GRANTED

    private var pendingBackupUrl: String? = null
    private var pendingBackupCookie: String? = null

    private val saveBackup =
        registerForActivityResult(ActivityResultContracts.CreateDocument("application/json")) { destination ->
            val url = pendingBackupUrl
            val cookie = pendingBackupCookie
            pendingBackupUrl = null
            pendingBackupCookie = null
            if (destination != null && url != null) {
                thread(name = "larder-backup") {
                    val connection = URL(url).openConnection() as HttpURLConnection
                    try {
                        connection.connectTimeout = 15000
                        connection.readTimeout = 30000
                        connection.instanceFollowRedirects = false
                        if (cookie != null) connection.setRequestProperty("Cookie", cookie)
                        check(connection.responseCode == HttpURLConnection.HTTP_OK) { "Could not download backup; reopen Settings and try again." }
                        contentResolver.openOutputStream(destination)?.use { output ->
                            connection.inputStream.use { input -> input.copyTo(output) }
                        } ?: error("Could not open the selected file")
                        runOnUiThread { Toast.makeText(this, "Backup saved", Toast.LENGTH_SHORT).show() }
                    } catch (e: Exception) {
                        runOnUiThread { Toast.makeText(this, e.message ?: "Backup failed", Toast.LENGTH_LONG).show() }
                    } finally {
                        connection.disconnect()
                    }
                }
            }
        }

    private val choosePhotos =
        registerForActivityResult(ActivityResultContracts.StartActivityForResult()) { result ->
            val data = result.data
            val uris: Array<Uri>? = when {
                result.resultCode != RESULT_OK -> null
                data?.clipData != null -> {
                    val clip = data.clipData!!
                    Array(clip.itemCount) { clip.getItemAt(it).uri }
                }
                data?.data != null -> arrayOf(data.data!!)
                cameraPhoto != null -> arrayOf(cameraPhoto!!) // the camera returns no data, just writes the file
                else -> null
            }
            pendingFiles?.onReceiveValue(uris) // null = cancelled; the web page must always get an answer
            pendingFiles = null
            cameraPhoto = null
        }

    @SuppressLint("SetJavaScriptEnabled")
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)

        // Debug builds: inspect the page from desktop Chrome at chrome://inspect.
        if (applicationInfo.flags and ApplicationInfo.FLAG_DEBUGGABLE != 0) {
            WebView.setWebContentsDebuggingEnabled(true)
        }

        web = WebView(this).apply {
            settings.javaScriptEnabled = true
            settings.domStorageEnabled = true
            settings.allowFileAccess = false
            settings.allowContentAccess = true
            webViewClient = AppClient()
            webChromeClient = PhotoChooser()
            setDownloadListener { url, _, _, _, _ ->
                val source = Uri.parse(url)
                val current = Uri.parse(this.url ?: "")
                if (source.scheme == "http" && source.host == "127.0.0.1" &&
                    source.authority == current.authority && source.path == "/api/backup") {
                    pendingBackupUrl = url
                    pendingBackupCookie = CookieManager.getInstance().getCookie(url)
                    saveBackup.launch("larder-backup.json")
                }
            }
            visibility = View.INVISIBLE // shown once the server answers
        }
        // WebView ignores its own padding, so pad a container instead to keep the
        // page clear of the status and navigation bars (Android 15 draws edge to edge).
        val root = FrameLayout(this).apply { addView(web) }
        setContentView(root)
        ViewCompat.setOnApplyWindowInsetsListener(root) { v, insets ->
            val bars = insets.getInsets(WindowInsetsCompat.Type.systemBars() or WindowInsetsCompat.Type.ime())
            v.setPadding(bars.left, bars.top, bars.right, bars.bottom)
            WindowInsetsCompat.CONSUMED
        }

        onBackPressedDispatcher.addCallback(this, object : OnBackPressedCallback(true) {
            override fun handleOnBackPressed() {
                if (web.canGoBack()) web.goBack() else finish()
            }
        })

        // Starting the server opens the data file, so keep it off the UI thread.
        thread(name = "larder-start") {
            try {
                val url = Larder.start(filesDir.absolutePath)
                runOnUiThread {
                    web.loadUrl(url)
                    web.visibility = View.VISIBLE
                }
            } catch (e: Exception) {
                runOnUiThread { showError(e.message ?: e.toString()) }
            }
        }
    }

    override fun onDestroy() {
        // Only stop the server when the user is really leaving, not on rotation.
        if (isFinishing) thread { Larder.stop() }
        web.destroy()
        super.onDestroy()
    }

    private fun showError(message: String) {
        setContentView(TextView(this).apply {
            text = "Larder couldn't start.\n\n$message"
            setPadding(48, 160, 48, 48)
            textSize = 16f
        })
    }

    /** Opens links to other sites in the browser instead of inside the app. */
    private inner class AppClient : WebViewClient() {
        override fun shouldOverrideUrlLoading(view: WebView, request: WebResourceRequest): Boolean {
            val url = request.url
            if (url.host == "127.0.0.1") return false
            startActivity(Intent(Intent.ACTION_VIEW, url))
            return true
        }
    }

    /** Makes image file inputs offer the camera and the gallery. */
    private inner class PhotoChooser : WebChromeClient() {
        /** getUserMedia from our own page (live barcode scan): ask Android, then answer the page. */
        override fun onPermissionRequest(request: PermissionRequest) {
            runOnUiThread {
                val ours = request.origin.host == "127.0.0.1"
                val wantsVideo = request.resources.contains(PermissionRequest.RESOURCE_VIDEO_CAPTURE)
                // Camera only: no microphone, and nothing for other sites.
                if (!ours || !wantsVideo || request.resources.any { it != PermissionRequest.RESOURCE_VIDEO_CAPTURE }) {
                    request.deny()
                } else if (hasCamera()) {
                    request.grant(arrayOf(PermissionRequest.RESOURCE_VIDEO_CAPTURE))
                } else {
                    pendingCameraRequest?.deny()
                    pendingCameraRequest = request
                    requestCamera.launch(Manifest.permission.CAMERA)
                }
            }
        }

        override fun onShowFileChooser(
            view: WebView,
            callback: ValueCallback<Array<Uri>>,
            params: FileChooserParams,
        ): Boolean {
            pendingFiles?.onReceiveValue(null)
            pendingFiles = callback
            cameraPhoto = null

            // Backup imports use the document picker; image inputs also offer the camera.
            if (!params.acceptTypes.any { it.startsWith("image/") }) {
                return try {
                    choosePhotos.launch(params.createIntent())
                    true
                } catch (e: Exception) {
                    pendingFiles = null
                    false
                }
            }

            val gallery = Intent(Intent.ACTION_GET_CONTENT).apply {
                type = "image/*"
                addCategory(Intent.CATEGORY_OPENABLE)
                putExtra(Intent.EXTRA_ALLOW_MULTIPLE, params.mode == FileChooserParams.MODE_OPEN_MULTIPLE)
            }

            // The camera app can only be offered once we hold the camera permission (we declare it).
            if (!hasCamera()) {
                afterCameraAnswer = { launchImageChooser(gallery) }
                requestCamera.launch(Manifest.permission.CAMERA)
                return true
            }
            return launchImageChooser(gallery)
        }

        private fun launchImageChooser(gallery: Intent): Boolean {
            val dir = File(cacheDir, "photos").apply { mkdirs() }
            val file = File.createTempFile("fridge-", ".jpg", dir)
            val photoUri = FileProvider.getUriForFile(this@MainActivity, "$packageName.photos", file)
            cameraPhoto = if (hasCamera()) photoUri else null
            val camera = Intent(MediaStore.ACTION_IMAGE_CAPTURE).apply {
                putExtra(MediaStore.EXTRA_OUTPUT, photoUri)
                addFlags(Intent.FLAG_GRANT_WRITE_URI_PERMISSION)
            }

            val chooser = Intent.createChooser(gallery, "Add photos").apply {
                // Without the permission, offer the gallery (and whatever it includes) only.
                if (hasCamera()) putExtra(Intent.EXTRA_INITIAL_INTENTS, arrayOf(camera))
            }
            return try {
                choosePhotos.launch(chooser)
                true
            } catch (e: Exception) {
                pendingFiles = null
                cameraPhoto = null
                false
            }
        }
    }
}
